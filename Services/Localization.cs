    public const string En = "en";
    public const string Vi = "vi";

    public static string Current { get; private set; } = Vi;

    public static event Action? LanguageChanged;

    public static void Set(string? lang)
    {
        string next = lang == En ? En : Vi;
        if (next == Current) return;
        Current = next;
        LanguageChanged?.Invoke();
    }

    public static string T(string key)
    {
        var dict = Current == En ? EnStrings : ViStrings;
        if (dict.TryGetValue(key, out var v)) return v;
        if (EnStrings.TryGetValue(key, out v)) return v;
        return key;
    }

    public static string T(string key, params object[] args)
    {
        try { return string.Format(T(key), args); }
        catch (FormatException) { return T(key); }
    }

    public static IReadOnlyDictionary<string, string> Strings(string lang) => lang == En ? EnStrings : ViStrings;

